import { PrismaClient } from "@prisma/client";

/**
 * Seeds the tradeable instruments across all asset classes (forex,
 * commodities, indices, crypto, stocks). User accounts are created through
 * the registration flow, not by the seed script.
 */
const prisma = new PrismaClient();

interface SeedInstrument {
  symbol: string;
  name: string;
  category: "FOREX" | "COMMODITY" | "INDEX" | "CRYPTO" | "STOCK";
  base: string;
  quote: string;
  digits: number;
  pipSize: string;
  pipValue: string;
  contractSize: string;
  marginPerLot: string;
  commissionPerLot: string;
  swapLongPips: string;
  swapShortPips: string;
  basePrice: string;
  feedSymbol: string;
}

function aiStock(symbol: string, name: string, basePrice: string): SeedInstrument {
  return {
    symbol,
    name,
    category: "STOCK",
    base: symbol,
    quote: "USD",
    digits: 2,
    pipSize: "0.01",
    pipValue: "1",
    contractSize: "1",
    marginPerLot: "25",
    commissionPerLot: "1",
    swapLongPips: "0",
    swapShortPips: "0",
    basePrice,
    feedSymbol: symbol,
  };
}

function cryptoInstrument(
  symbol: string,
  name: string,
  basePrice: string,
  digits: number,
): SeedInstrument {
  const base = symbol.slice(0, -3);
  return {
    symbol,
    name,
    category: "CRYPTO",
    base,
    quote: "USD",
    digits,
    pipSize: (10 ** -digits).toFixed(digits),
    pipValue: "1",
    contractSize: "1",
    marginPerLot: "1000",
    commissionPerLot: "7",
    swapLongPips: "5",
    swapShortPips: "2.5",
    basePrice,
    feedSymbol: `BINANCE:${base}USDT`,
  };
}

