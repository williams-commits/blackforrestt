async function main() {
  console.log("🌱 Seeding instruments…");
  for (const i of INSTRUMENTS) {
    await prisma.instrument.upsert({
      where: { symbol: i.symbol },
      update: {
        name: i.name,
        category: i.category,
        base: i.base,
        quote: i.quote,
        digits: i.digits,
        pipSize: i.pipSize,
        pipValue: i.pipValue,
        contractSize: i.contractSize,
        marginPerLot: i.marginPerLot,
        commissionPerLot: i.commissionPerLot,
        swapLongPips: i.swapLongPips,
        swapShortPips: i.swapShortPips,
        basePrice: i.basePrice,
        feedSymbol: i.feedSymbol,
      },
      create: { ...i },
    });
    console.log(`  ✓ ${i.symbol}`);
  }

  await prisma.instrument.updateMany({
    where: { symbol: "VIX" },
    data: { active: true },
  });

  await prisma.instrument.updateMany({
    where: { symbol: "MATICUSD" },
    data: { active: false },
  });

  console.log("✅ Seed complete.");
}

main()
  .catch((e) => {
    console.error("❌ Seed failed:", e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
